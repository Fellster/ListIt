import assert from 'node:assert/strict';
import {orderedItems,reorderTabs,firstList} from '../src/redesign/model.ts';
const items=['a','b','c'].map(id=>({id,title:id,done:false,fields:{}}));
const shared={id:'shared',name:'Shared',template:'Other',group:'Personal',sharedId:'shared',items};
const alice={version:1,defaultTheme:'blue',lists:[shared],itemOrders:{shared:['c','a','b']}};
const bob={version:1,defaultTheme:'blue',lists:[shared],itemOrders:{shared:['b','a','c']}};
assert.deepEqual(orderedItems(items,alice.itemOrders.shared).map(i=>i.id),['c','a','b']);
assert.deepEqual(orderedItems(items,bob.itemOrders.shared).map(i=>i.id),['b','a','c']);
assert.deepEqual(shared.items.map(i=>i.id),['a','b','c'],'Shared content must not be rearranged');
const changed=reorderTabs(orderedItems(items,alice.itemOrders.shared).map(i=>i.id),'c','b');
assert.deepEqual(changed,['a','b','c']);
assert.deepEqual(bob.itemOrders.shared,['b','a','c'],'Another account order is independent');
assert.deepEqual(orderedItems([...items,{id:'new'}],['removed',...alice.itemOrders.shared]).map(i=>i.id),['c','a','b','new'],'Deleted IDs are ignored and new items append');
assert.deepEqual(orderedItems(items.filter(i=>i.id!=='a'),alice.itemOrders.shared).map(i=>i.id),['c','b']);
assert.deepEqual(orderedItems(JSON.parse(JSON.stringify(items)),JSON.parse(JSON.stringify(alice.itemOrders.shared))).map(i=>i.id),['c','a','b'],'Cloud roundtrip retains personal order');
const state={...alice,lists:[shared,{...shared,id:'work1',group:'Work'},{...shared,id:'work2',group:'Work'},{...shared,id:'personal2'}],listOrder:['work2','personal2','work1','shared']};
assert.equal(firstList(state,'Personal').id,'personal2');
assert.equal(firstList(state,'Work').id,'work2');
assert.equal(firstList({...state,lists:[]},'Work'),undefined);
console.log('PASS: independent account order, unchanged shared content, new/deleted items, persistence, and first tab in each group');
